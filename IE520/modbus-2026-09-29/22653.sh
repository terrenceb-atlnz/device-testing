#!/bin/bash
# T22653 modbus - read port information. Console = stack master /dev/u5; client = tb470 eth1 -> vlan1 10.38.215.10:502
cd /tmp/ckmodbus
C="python3 ckcon.py /dev/u5 115200 /tmp/ckmodbus/console-u5.log"
M="python3 mb.py --log /tmp/ckmodbus/mb-22653.log"
echo "### $(date) T22653 enable modbus server (read-only default)"
$C --stop-on-error "configure terminal" "scada modbus tcp server" "end" "show scada modbus tcp server" "show running-config | include scada" || { echo ENABLE-FAILED; exit 2; }
sleep 2
echo "### $(date) mapping / discovery"
$M read 0x0000 1 UINT "mapping version, slave 0"
$M --slave 1 read 0x0000 1 UINT "mapping version, slave 1"
$M read 0x0000 125 RAW "system block 0x0000-0x007c, slave 0"
$M --slave 1 read 0x0120 5 RAW "member-1 system info 0x0120-0x0124"
$M --slave 1 read 0x0200 3 RAW "member-1 board class/slot 0x0200"
echo "### $(date) steps 1-7: port #1 = port1.0.1 (member 1, index 0), slave 1"
$M --slave 1 read 0x5000 1 HEX "step1 #1 Port Current State (R)"
$M --slave 1 read 0x5001 1 HEX "step2 #1 Port Configured State (RW)"
$M --slave 1 read 0x5002 1 HEX "step3 #1 Port PoE Configuration (RW)"
$M --slave 1 read 0x5003 1 UINT "step4 #1 Port PoE Data Pairs Power (R)"
$M --slave 1 read 0x5004 1 UINT "step5 #1 Port PoE Spare Pairs Power (R)"
$M --slave 1 read 0x5005 4 UINT "step6 #1 Port Input Bytes (R)"
$M --slave 1 read 0x5009 4 UINT "step7 #1 Port Output Bytes (R)"
$M --slave 1 read 0x5000 13 RAW "port index 0 whole block"
echo "### $(date) extra: port #2 = port1.0.2 (linked, LAG member), slave 1, block at 0x500d"
$M --slave 1 read 0x500d 13 RAW "port index 1 whole block"
$M --slave 1 read 0x500d 1 HEX "#2 current state"
$M --slave 1 read 0x500e 1 HEX "#2 configured state"
$M --slave 1 read 0x5012 4 UINT "#2 input bytes"
$M --slave 1 read 0x5016 4 UINT "#2 output bytes"
echo "### $(date) other unit ids"
$M --slave 0 read 0x5000 13 RAW "slave 0 port block"
$M --slave 3 read 0x5000 13 RAW "member 3 index 0 (port3.0.1)"
$M --slave 3 read 0x50a1 13 RAW "member 3 index 12 (port3.0.13, tb eth1 link)"
$M --slave 2 read 0x5000 1 HEX "member 2 (provisioned, absent)"
echo "### $(date) CLI right after the reads"
$C "show interface port1.0.1" "show interface port1.0.1 status" "show interface port1.0.2" "show interface port1.0.2 status" "show interface port3.0.13" "show power-inline interface port1.0.1" "show scada modbus tcp server" "show scada modbus tcp server connections"
echo "### $(date) done"
